#!/usr/bin/env bun
/**
 * Refreshes the bundled models.dev catalog snapshot at
 * src/provider/models-snapshot.txt.
 * The snapshot is the boot-time floor for the catalog when no cache entry
 * exists and fetching is disabled or unavailable; live fetch still refreshes
 * on top. Ported from opencode's
 * packages/core/script/update-models-snapshot.ts.
 */
const source = process.env.NAVI_MODELS_URL || "https://models.dev"
const response = await fetch(`${source}/api.json`)
if (!response.ok) {
  console.error(`Failed to fetch ${source}/api.json: ${response.status} ${response.statusText}`)
  process.exit(1)
}
const text = await response.text()
const parsed: unknown = JSON.parse(text)
// A floor, not equality: guards against committing an error page or a
// truncated body that still parses as a small object.
const MINIMUM_PROVIDERS = 100
if (typeof parsed !== "object" || parsed === null || Object.keys(parsed).length < MINIMUM_PROVIDERS) {
  console.error(`Fetched catalog has fewer than ${MINIMUM_PROVIDERS} providers; refusing to write snapshot`)
  process.exit(1)
}
const target = new URL("../src/provider/models-snapshot.txt", import.meta.url)
await Bun.write(target, text)
// Keep the build-generated ESM snapshot in sync so `bun run build`
// (script/generate.ts) and dev both see the same catalog.
await Bun.write(
  new URL("../src/provider/models-snapshot.js", import.meta.url),
  `// @ts-nocheck\n// Auto-generated by build.ts - do not edit\nexport const snapshot = ${text}\n`,
)
console.log(`Wrote ${Object.keys(parsed).length} providers (${text.length} bytes) to ${Bun.fileURLToPath(target)}`)
